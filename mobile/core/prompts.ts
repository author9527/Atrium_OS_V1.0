/** 把用户自定义 ego 拼成【你的人格设定】区块；无 ego 时返回空串。 */
export function egoSection(egoParts: string[] | null | undefined): string {
  const parts = (egoParts || []).filter((p) => p && p.trim());
  if (!parts.length) return '';
  return '【你的人格设定】\n' + parts.join('\n');
}

export function buildEmpathySystem(egoParts: string[] | null | undefined): string {
  return EMPATHY_SYSTEM_CORE
    .replace('{ego_section}', egoSection(egoParts))
    .replace('{reply_norms}', REPLY_NORMS);
}

export function buildAwarenessSystem(egoParts: string[] | null | undefined): string {
  return AWARENESS_SYSTEM_CORE
    .replace('{ego_section}', egoSection(egoParts))
    .replace('{reply_norms}', REPLY_NORMS);
}

export function buildGreetingSystem(dateStr: string = ''): string {
  return GREETING_SYSTEM_CORE.replace('{date_str}', dateStr);
}